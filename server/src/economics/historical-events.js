// ── GET EVENT BY PLAYER LEVEL ──
export function getHistoricalEvent(playerLevel) {
  // Events are one-time. Player level determines which events are available.
  // Level 5-15: Hamster, Squid, Doge SNL
  // Level 15-30: Melania, LUNA, FTX, 3AC
  // Level 30-45: China Mining, Celsius, Voyager, Mt.Gox, DAO Hack, El Salvador, Tesla BTC
  // Level 45-50: Black Thursday
  const available = HISTORICAL_EVENTS.filter(e => playerLevel >= e.level - 3 && playerLevel <= e.level + 5);
  if (available.length === 0) return null;
  return available[Math.floor(Math.random() * available.length)];
}

export function getEventById(id) {
  return HISTORICAL_EVENTS.find(e => e.id === id) || null;
}

